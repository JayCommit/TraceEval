import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { TraceEvent } from "../types/index.js";
import { resolveSessionId } from "./session.js";
import {
  createEventId,
  normalizeHookType,
  truncatePayload,
  safeJsonParse,
  updateJsonFile,
  backupAndWriteFile,
} from "./common.js";

export interface GrokBotHookPayload {
  session_id?: string;
  sessionId?: string;
  bot_id?: string;
  botId?: string;
  event?: string;
  action?: string;
  tool?: string;
  tool_name?: string;
  command?: string;
  input?: unknown;
  args?: unknown;
  output?: unknown;
  result?: unknown;
  duration_ms?: number;
  durationMs?: number;
  prompt?: string;
  message?: string;
  error?: string;
  status?: string;
  tokens?: {
    input?: number;
    output?: number;
    total?: number;
  };
  usage?: {
    prompt_tokens?: number;
    completion_tokens?: number;
    total_tokens?: number;
  };
  [key: string]: unknown;
}

export interface ParseGrokBotOptions {
  sessionId?: string;
  baseDir?: string;
  debug?: boolean;
}

export function getGrokBotConfigPaths(global = false, cwd = process.cwd()): {
  botDir: string;
  pluginsDir: string;
  pluginPath: string;
  configPath: string;
} {
  const botDir = global ? path.join(os.homedir(), ".grok-bot") : path.join(cwd, ".grok-bot");
  const pluginsDir = path.join(botDir, "plugins");
  const pluginPath = path.join(pluginsDir, "traceeval.js");
  const configPath = path.join(botDir, "config.json");
  return { botDir, pluginsDir, pluginPath, configPath };
}

/**
 * Installs TraceEval bot adapter and plugin hooks for Grok Bot.
 */
export function installGrokBotHooks(options: {
  global?: boolean;
  cwd?: string;
  binaryPath?: string;
}): {
  configPath: string;
  pluginPath: string;
  backupPath?: string;
} {
  const cwd = options.cwd || process.cwd();
  const bin = options.binaryPath || "traceeval";
  const { pluginsDir, pluginPath, configPath } = getGrokBotConfigPaths(options.global, cwd);

  if (!fs.existsSync(pluginsDir)) {
    fs.mkdirSync(pluginsDir, { recursive: true });
  }

  const pluginContent = `// TraceEval Grok Bot Plugin Adapter
// Auto-generated by traceeval install grok-bot
const { spawn } = require("node:child_process");

module.exports = {
  name: "traceeval-grok-bot",
  version: "1.0.0",

  onBotStart(context) {
    emitHook("start", { sessionId: context.sessionId || context.id, prompt: context.prompt, agent: "grok-bot" });
  },

  onBotTool(toolCall) {
    emitHook("pre-tool", {
      sessionId: toolCall.sessionId,
      tool: toolCall.name || toolCall.tool,
      input: toolCall.args || toolCall.input,
      agent: "grok-bot"
    });
  },

  onBotResult(result) {
    emitHook("post-tool", {
      sessionId: result.sessionId,
      tool: result.name || result.tool,
      output: result.output || result.result,
      durationMs: result.durationMs,
      status: result.error ? "error" : "success",
      error: result.error,
      agent: "grok-bot"
    });
  },

  onBotEnd(context) {
    emitHook("stop", { sessionId: context.sessionId || context.id, agent: "grok-bot" });
  }
};

function emitHook(type, payload) {
  try {
    const child = spawn("${bin}", ["hook", type, "--agent", "grok-bot", "--data", JSON.stringify(payload)], {
      detached: true,
      stdio: "ignore"
    });
    child.unref();
  } catch {
    // Fail silently
  }
}
`;

  const writeResult = backupAndWriteFile(pluginPath, pluginContent);

  updateJsonFile<Record<string, unknown>>(configPath, (existing) => {
    const plugins = Array.isArray(existing.plugins) ? (existing.plugins as string[]) : [];
    if (!plugins.includes("plugins/traceeval.js")) {
      plugins.push("plugins/traceeval.js");
    }
    return {
      ...existing,
      botName: "grok-bot",
      plugins,
    };
  });

  return {
    configPath,
    pluginPath,
    backupPath: writeResult.backupPath,
  };
}

/**
 * Parses Grok Bot payloads into standardized TraceEvent format.
 */
export function parseGrokBotHookPayload(
  hookType: string,
  rawPayload: string | Record<string, unknown>,
  sessionOrOptions?: string | ParseGrokBotOptions
): TraceEvent {
  const options: ParseGrokBotOptions =
    typeof sessionOrOptions === "string"
      ? { sessionId: sessionOrOptions }
      : sessionOrOptions || {};

  const parsed = safeJsonParse<GrokBotHookPayload>(rawPayload, {});

  const sessionId = resolveSessionId({
    explicitId: options.sessionId,
    payload: parsed,
    baseDir: options.baseDir,
  });

  const eventId = createEventId("grok-bot");
  const timestamp = new Date().toISOString();
  const normalized = normalizeHookType(hookType || parsed.action || parsed.event || "");

  let eventType: TraceEvent["type"] = "custom";
  const data: Record<string, unknown> = truncatePayload({ ...parsed }) as Record<string, unknown>;

  if (parsed.usage) {
    data.tokens = {
      input: parsed.usage.prompt_tokens,
      output: parsed.usage.completion_tokens,
      total: parsed.usage.total_tokens,
    };
  }

  switch (normalized) {
    case "start":
    case "sessionstart":
    case "botstart":
      eventType = "session_start";
      break;

    case "prompt":
    case "userprompt":
    case "mention":
      eventType = "user_prompt";
      data.prompt = parsed.prompt || parsed.message || "";
      break;

    case "pretool":
    case "pretooluse":
    case "bottool":
      eventType = "tool_call_start";
      data.toolName = parsed.action || parsed.tool || parsed.tool_name || parsed.command || "unknown";
      data.input = parsed.input ?? parsed.args;
      break;

    case "posttool":
    case "posttooluse":
    case "botresult":
      eventType = "tool_call";
      data.toolName = parsed.action || parsed.tool || parsed.tool_name || parsed.command || "unknown";
      data.input = parsed.input ?? parsed.args;
      data.output = parsed.output ?? parsed.result;
      data.durationMs = parsed.duration_ms ?? parsed.durationMs;
      data.status = parsed.error ? "error" : parsed.status || "success";
      break;

    case "file":
    case "filechange":
    case "filewrite":
      eventType = "file_change";
      data.path = (parsed.path || parsed.file || "unknown") as string;
      data.changeType = (parsed.status || "modified") as string;
      break;

    case "stop":
    case "sessionend":
    case "botend":
      eventType = "session_end";
      data.durationMs = parsed.duration_ms ?? parsed.durationMs;
      break;
  }

  return {
    id: eventId,
    sessionId,
    timestamp,
    type: eventType,
    agent: "grok-bot",
    data,
  };
}
