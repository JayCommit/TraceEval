import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import crypto from "node:crypto";
import { TraceEvent } from "../types/index.js";
import { resolveSessionId } from "./session.js";

export interface OpenCodeHookPayload {
  session_id?: string;
  sessionId?: string;
  type?: string;
  event?: string;
  tool?: string;
  tool_name?: string;
  toolName?: string;
  command?: string;
  input?: unknown;
  args?: unknown;
  parameters?: unknown;
  output?: unknown;
  result?: unknown;
  duration_ms?: number;
  durationMs?: number;
  status?: string;
  error?: string;
  path?: string;
  file?: string;
  filePath?: string;
  prompt?: string;
  message?: string;
  raw?: string;
  [key: string]: unknown;
}

export interface ParseOpenCodeOptions {
  sessionId?: string;
  baseDir?: string;
  debug?: boolean;
}

/**
 * Returns the path to the OpenCode plugin configuration directory.
 */
export function getOpenCodeConfigPath(global = false, cwd = process.cwd()): {
  pluginsDir: string;
  pluginFile: string;
  configPath: string;
} {
  const rootDir = global ? path.join(os.homedir(), ".opencode") : path.join(cwd, ".opencode");
  const pluginsDir = path.join(rootDir, "plugins");
  const pluginFile = path.join(pluginsDir, "traceeval.js");
  const configPath = path.join(rootDir, "config.json");
  return { pluginsDir, pluginFile, configPath };
}

/**
 * Installs the TraceEval plugin adapter into the OpenCode configuration.
 */
export function installOpenCodePlugin(options: {
  global?: boolean;
  cwd?: string;
  binaryPath?: string;
}): { configPath: string; pluginPath: string; backupPath?: string } {
  const cwd = options.cwd || process.cwd();
  const { pluginsDir, pluginFile, configPath } = getOpenCodeConfigPath(options.global, cwd);

  if (!fs.existsSync(pluginsDir)) {
    fs.mkdirSync(pluginsDir, { recursive: true });
  }

  const bin = options.binaryPath || "traceeval";

  // Standalone OpenCode plugin code
  const pluginCode = `// TraceEval OpenCode Plugin Adapter
// Auto-generated by traceeval install opencode
const { spawn } = require("node:child_process");

module.exports = {
  name: "traceeval-opencode",
  version: "1.0.0",

  onSessionStart(session) {
    emitHook("start", { sessionId: session.id, prompt: session.prompt, agent: "opencode" });
  },

  onToolExecute(toolCall) {
    emitHook("pre-tool", {
      sessionId: toolCall.sessionId,
      tool: toolCall.name,
      input: toolCall.args || toolCall.input,
      agent: "opencode"
    });
  },

  onToolComplete(result) {
    emitHook("post-tool", {
      sessionId: result.sessionId,
      tool: result.name,
      output: result.output,
      durationMs: result.durationMs,
      status: result.error ? "error" : "success",
      error: result.error,
      agent: "opencode"
    });
  },

  onFileChange(change) {
    emitHook("file", {
      sessionId: change.sessionId,
      path: change.path || change.file,
      changeType: change.type || "modified",
      agent: "opencode"
    });
  },

  onSessionEnd(session) {
    emitHook("stop", { sessionId: session.id, agent: "opencode" });
  }
};

function emitHook(type, payload) {
  try {
    const child = spawn("${bin}", ["hook", type, "--data", JSON.stringify(payload)], {
      detached: true,
      stdio: "ignore"
    });
    child.unref();
  } catch {
    // Fail silently to never interrupt OpenCode
  }
}
`;

  fs.writeFileSync(pluginFile, pluginCode, "utf-8");

  // Update or create config.json
  let config: Record<string, unknown> = {};
  let backupPath: string | undefined;

  if (fs.existsSync(configPath)) {
    try {
      const raw = fs.readFileSync(configPath, "utf-8");
      config = JSON.parse(raw);
      backupPath = `${configPath}.bak.${Date.now()}`;
      fs.writeFileSync(backupPath, raw, "utf-8");
    } catch {
      config = {};
    }
  }

  const existingPlugins = Array.isArray(config.plugins) ? (config.plugins as string[]) : [];
  if (!existingPlugins.includes(pluginFile) && !existingPlugins.includes("plugins/traceeval.js")) {
    config.plugins = [...existingPlugins, "plugins/traceeval.js"];
  }

  fs.writeFileSync(configPath, JSON.stringify(config, null, 2), "utf-8");

  return { configPath, pluginPath: pluginFile, backupPath };
}

/**
 * Parses an OpenCode event payload into a standardized TraceEvent.
 */
export function parseOpenCodeHookPayload(
  hookType: string,
  rawPayload: string | Record<string, unknown>,
  sessionOrOptions?: string | ParseOpenCodeOptions
): TraceEvent {
  const options: ParseOpenCodeOptions =
    typeof sessionOrOptions === "string"
      ? { sessionId: sessionOrOptions }
      : sessionOrOptions || {};

  let parsed: OpenCodeHookPayload = {};
  if (typeof rawPayload === "string") {
    try {
      if (rawPayload && rawPayload.trim().length > 0) {
        parsed = JSON.parse(rawPayload) as OpenCodeHookPayload;
      }
    } catch {
      parsed = { raw: rawPayload };
    }
  } else if (rawPayload && typeof rawPayload === "object") {
    parsed = rawPayload as OpenCodeHookPayload;
  }

  const sessionId = resolveSessionId({
    explicitId: options.sessionId,
    payload: parsed,
    baseDir: options.baseDir,
  });

  const eventId = `evt-opencode-${Date.now()}-${crypto.randomBytes(3).toString("hex")}`;
  const timestamp = new Date().toISOString();

  const normalized = (hookType || parsed.type || parsed.event || "")
    .toLowerCase()
    .replace(/[-_.]/g, "");

  let eventType: TraceEvent["type"] = "custom";
  const data: Record<string, unknown> = { ...parsed };

  switch (normalized) {
    case "start":
    case "sessionstart":
      eventType = "session_start";
      break;

    case "prompt":
    case "userprompt":
      eventType = "user_prompt";
      data.prompt = parsed.prompt || parsed.message || parsed.input || "";
      break;

    case "pretool":
    case "toolexecute":
    case "toolcall":
      eventType = "tool_call_start";
      data.toolName = parsed.tool || parsed.tool_name || parsed.toolName || "unknown";
      data.input = parsed.input ?? parsed.args ?? parsed.parameters ?? parsed.command;
      break;

    case "posttool":
    case "toolcomplete":
    case "toolresult":
      eventType = "tool_call";
      data.toolName = parsed.tool || parsed.tool_name || parsed.toolName || "unknown";
      data.input = parsed.input ?? parsed.args ?? parsed.parameters ?? parsed.command;
      data.output = parsed.output ?? parsed.result;
      data.durationMs = parsed.duration_ms ?? parsed.durationMs;
      data.status = parsed.error ? "error" : parsed.status || "success";
      break;

    case "file":
    case "filechange":
    case "filewrite":
      eventType = "file_change";
      data.path = parsed.path || parsed.file || parsed.filePath || "unknown";
      data.changeType = parsed.status || "modified";
      break;

    case "stop":
    case "sessionend":
      eventType = "session_end";
      data.durationMs = parsed.duration_ms ?? parsed.durationMs;
      break;
  }

  return {
    id: eventId,
    sessionId,
    timestamp,
    type: eventType,
    agent: "opencode",
    data,
  };
}
